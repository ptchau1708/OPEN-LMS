function svgUri(svg: string): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg.replace(/\s{2,}/g, ' ').trim())}`;
}

const FONT = "font-family='Nunito, Arial, sans-serif' font-weight='700'";

/** Biểu đồ cột: số cây 4 tổ trồng được (12, 18, 15, 11). */
const BAR_CHART = (() => {
  const data: [string, number][] = [['Tổ 1', 12], ['Tổ 2', 18], ['Tổ 3', 15], ['Tổ 4', 11]];
  const H = 200;
  const unit = 9; // px mỗi cây
  const bars = data
    .map(([label, v], i) => {
      const x = 70 + i * 80;
      const h = v * unit;
      return `<rect x='${x}' y='${H + 20 - h}' width='44' height='${h}' rx='4' fill='#2f7bf6'/>
        <text x='${x + 22}' y='${H + 42}' text-anchor='middle' font-size='15' ${FONT} fill='#334155'>${label}</text>`;
    })
    .join('');
  const ticks = [0, 5, 10, 15, 20]
    .map((t) => `<line x1='55' x2='390' y1='${H + 20 - t * unit}' y2='${H + 20 - t * unit}' stroke='#cbd5e1' stroke-dasharray='4 4'/>
      <text x='48' y='${H + 25 - t * unit}' text-anchor='end' font-size='13' ${FONT} fill='#64748b'>${t}</text>`)
    .join('');
  return svgUri(`<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 400 260'><rect width='400' height='260' fill='#fff'/>${ticks}${bars}
    <text x='200' y='14' text-anchor='middle' font-size='14' ${FONT} fill='#0f172a'>Số cây mỗi tổ trồng được</text></svg>`);
})();

