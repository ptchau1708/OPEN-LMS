/** Hình tròn chia 8 phần bằng nhau, tô 3 phần. */
const CIRCLE_3_8 = (() => {
  const parts: string[] = [];
  for (let i = 0; i < 8; i++) {
    const a1 = (i * Math.PI) / 4 - Math.PI / 2;
    const a2 = ((i + 1) * Math.PI) / 4 - Math.PI / 2;
    const p = (a: number) => `${(100 + 80 * Math.cos(a)).toFixed(1)} ${(100 + 80 * Math.sin(a)).toFixed(1)}`;
    parts.push(`<path d='M100 100 L${p(a1)} A80 80 0 0 1 ${p(a2)} Z' fill='${i < 3 ? '#ff8a3d' : '#fff7ed'}' stroke='#9a3412' stroke-width='2'/>`);
  }
  return svgUri(`<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 200 200'>${parts.join('')}</svg>`);
})();

