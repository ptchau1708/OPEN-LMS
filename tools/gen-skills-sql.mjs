#!/usr/bin/env node
/**
 * Sinh supabase/seed/skills.sql từ danh mục TypeScript (nguồn sự thật):
 *   packages/contracts/src/skills-toan.ts, skills-provisional.ts, skills-ct2018.ts, skills-misconceptions.ts
 *   packages/data/src/seed/skill-tags.ts (câu hỏi cũ) + items-toan45.ts (câu mới, trường `skills`)
 *
 *   node tools/gen-skills-sql.mjs          # ghi file
 *   node tools/gen-skills-sql.mjs --check  # thoát mã 1 nếu file đã cũ (CI)
 *
 * Cần Node ≥ 22.18 (tự bỏ kiểu TypeScript khi import .ts). Các file nguồn chỉ dùng `import type` nên nạp trực tiếp được.
 * Chạy SQL sau migration 20261111000001_v2_skills.sql (SQL Editor hoặc `psql -f`). Chạy lại được (upsert).
 */
import { promises as fs, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'supabase', 'seed', 'skills.sql');
const CHECK = process.argv.includes('--check');
const load = (p) => import(pathToFileURL(path.join(ROOT, p)).href);

const { TOAN_SKILLS } = await load('packages/contracts/src/skills-toan.ts');
const { PROVISIONAL_SKILLS } = await load('packages/contracts/src/skills-provisional.ts');
const { CT2018_SKILLS } = await load('packages/contracts/src/skills-ct2018.ts');
const { MISCONCEPTION_LIST } = await load('packages/contracts/src/skills-misconceptions.ts');
const { LEGACY_SKILL_TAGS } = await load('packages/data/src/seed/skill-tags.ts');
const { TOAN45_ITEMS } = await load('packages/data/src/seed/items-toan45.ts');

const skills = [...TOAN_SKILLS, ...PROVISIONAL_SKILLS, ...CT2018_SKILLS];
const codes = new Set(skills.map((s) => s.code));
const errors = [];
for (const s of skills) for (const p of s.prereqs) if (!codes.has(p)) errors.push(`${s.code}: prereq lạ ${p}`);
const tags = { ...LEGACY_SKILL_TAGS };
for (const it of TOAN45_ITEMS) tags[it.id] = it.skills ?? [];
for (const [id, list] of Object.entries(tags)) for (const c of list) if (!codes.has(c)) errors.push(`${id}: mã kĩ năng lạ ${c}`);
for (const m of MISCONCEPTION_LIST) for (const c of [m.skill, m.rootSkill].filter(Boolean)) if (!codes.has(c)) errors.push(`${m.code}: mã kĩ năng lạ ${c}`);
if (errors.length) {
  console.error('gen-skills-sql: LỖI\n  ' + errors.join('\n  '));
  process.exit(1);
}

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => (xs.length ? `array[${xs.map(q).join(', ')}]::text[]` : `'{}'::text[]`);

const lines = [
  '-- GENERATED by tools/gen-skills-sql.mjs — KHÔNG sửa tay. Sửa packages/contracts/src/skills-*.ts rồi chạy lại.',
  '-- Chạy sau migration 20261111000001_v2_skills.sql. Upsert: chạy lại bao nhiêu lần cũng được.',
  `-- ${skills.length} kĩ năng (${TOAN_SKILLS.length} Toán, ${PROVISIONAL_SKILLS.length} tạm, ${CT2018_SKILLS.length} theo chủ đề CT 2018), ${MISCONCEPTION_LIST.length} quan niệm sai, ${Object.values(tags).flat().length} gắn thẻ câu hỏi.`,
  'begin;',
  '',
  'insert into v2.skills (code, subject, grade, strand, topic, text, short, prereqs, provisional, position) values',
  skills
    .map((s, i) => `  (${q(s.code)}, ${q(s.subject)}, ${s.grade}, ${q(s.strand)}, ${q(s.topic)}, ${q(s.text)}, ${q(s.short)}, ${arr(s.prereqs)}, ${s.provisional ? 'true' : 'false'}, ${i})`)
    .join(',\n'),
  'on conflict (code) do update set subject = excluded.subject, grade = excluded.grade, strand = excluded.strand, topic = excluded.topic,',
  '  text = excluded.text, short = excluded.short, prereqs = excluded.prereqs, provisional = excluded.provisional, position = excluded.position, updated_at = now();',
  '',
  'insert into v2.misconceptions (code, text, kid_hint, skill_code, root_skill) values',
  MISCONCEPTION_LIST.map((m) => `  (${q(m.code)}, ${q(m.text)}, ${q(m.kidHint)}, ${q(m.skill)}, ${q(m.rootSkill ?? null)})`).join(',\n'),
  'on conflict (code) do update set text = excluded.text, kid_hint = excluded.kid_hint, skill_code = excluded.skill_code, root_skill = excluded.root_skill;',
  '',
  '-- Gắn thẻ câu hỏi mẫu (chỉ những item đã có trong v2.items).',
  'insert into v2.item_skills (item_id, skill_code, position)',
  'select v.item_id, v.skill_code, v.position from (values',
  Object.entries(tags)
    .flatMap(([id, list]) => list.map((c, i) => `  (${q(id)}, ${q(c)}, ${i})`))
    .join(',\n'),
  ') as v(item_id, skill_code, position)',
  'where exists (select 1 from v2.items i where i.id = v.item_id)',
  'on conflict (item_id, skill_code) do update set position = excluded.position;',
  '',
  '-- Bổ sung result.skills cho sự kiện trả lời cũ (trước migration) để Edge Function tính được mức thành thạo.',
  'update v2.learning_events e',
  "   set result = coalesce(e.result, '{}'::jsonb) || jsonb_build_object('skills', s.skills)",
  '  from (select item_id, jsonb_agg(skill_code order by position) as skills from v2.item_skills group by item_id) s',
  " where e.verb = 'answered' and e.object_type = 'item' and e.object_id = s.item_id and not (coalesce(e.result, '{}'::jsonb) ? 'skills');",
  '',
  'commit;',
  '',
];
const sql = lines.join('\n');
const old = existsSync(OUT) ? await fs.readFile(OUT, 'utf8') : null;
if (CHECK) {
  if (old !== sql) {
    console.error('supabase/seed/skills.sql đã cũ — chạy: node tools/gen-skills-sql.mjs');
    process.exit(1);
  }
  console.log('gen-skills-sql: không đổi');
} else {
  await fs.mkdir(path.dirname(OUT), { recursive: true });
  await fs.writeFile(OUT, sql);
  console.log(`gen-skills-sql: ${skills.length} kĩ năng, ${MISCONCEPTION_LIST.length} quan niệm sai → ${path.relative(ROOT, OUT)}`);
}
