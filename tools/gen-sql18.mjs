#!/usr/bin/env node
/**
 * Sinh supabase/migrations/20261124000004_v2_user_prefs_skills.sql (SQL 18):
 *   1) mở rộng v2.skills.strand thêm 'CHU-DE';
 *   2) bảng v2.user_prefs (cài đặt cá nhân đồng bộ giữa các máy);
 *   3) upsert kĩ năng theo chủ đề CT GDPT 2018 (packages/contracts/src/skills-ct2018.ts).
 *   node tools/gen-sql18.mjs [--check]
 */
import { promises as fs, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'supabase', 'migrations', '20261124000004_v2_user_prefs_skills.sql');
const { CT2018_SKILLS } = await import(pathToFileURL(path.join(ROOT, 'packages/contracts/src/skills-ct2018.ts')).href);
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const sql = `-- =============================================================================
-- OPEN-EDU · SQL 18 · Cài đặt cá nhân đồng bộ giữa các máy + kĩ năng các môn theo CT GDPT 2018
-- GENERATED by tools/gen-sql18.mjs — KHÔNG sửa tay.
--
-- 1) v2.skills.strand thêm 'CHU-DE' (kĩ năng theo chủ đề của các môn ngoài Toán).
-- 2) v2.user_prefs: mỗi người dùng lưu cài đặt của mình (vd môn hiện trên bản đồ kiến thức từng lớp);
--    RLS: chỉ đọc / ghi hàng của chính mình. Tối đa 300 cài đặt, mỗi cài đặt ≤ 16 KB.
-- 3) ${CT2018_SKILLS.length} kĩ năng theo chủ đề CT GDPT 2018 (Tiếng Việt, Tiếng Anh, Đạo đức, TN&XH, LS&ĐL, Khoa học,
--    Tin học, Công nghệ, GDTC, Âm nhạc, Mĩ thuật, HĐTN) — mô tả tóm lược, provisional = true.
-- Cần chạy SAU SQL 17 (môn học GDPT 2018). Chạy lại được (idempotent).
-- =============================================================================
begin;

-- 1) Mạch 'CHU-DE' --------------------------------------------------------------
do $$
declare r record;
begin
  for r in
    select c.conname from pg_constraint c
      join pg_class t on t.oid = c.conrelid join pg_namespace n on n.oid = t.relnamespace
     where n.nspname = 'v2' and t.relname = 'skills' and c.contype = 'c' and pg_get_constraintdef(c.oid) like '%TAM-THOI%'
  loop
    execute format('alter table v2.skills drop constraint %I', r.conname);
  end loop;
end $$;
alter table v2.skills add constraint skills_strand_check
  check (strand in ('SO-PHEP-TINH', 'HINH-DO-LUONG', 'THONG-KE-XAC-SUAT', 'TAM-THOI', 'CHU-DE'));

-- 2) Cài đặt cá nhân --------------------------------------------------------------
create table if not exists v2.user_prefs (
  user_id uuid not null references v2.profiles (id) on delete cascade,
  key text not null check (key ~ '^[a-z0-9][a-z0-9._-]{0,119}$'),
  value jsonb not null check (pg_column_size(value) <= 16384),
  updated_at timestamptz not null default now(),
  primary key (user_id, key)
);
comment on table v2.user_prefs is 'Cài đặt cá nhân (packages/data/src/prefs). Mỗi người chỉ thấy hàng của mình.';

drop trigger if exists user_prefs_updated_at on v2.user_prefs;
create trigger user_prefs_updated_at before update on v2.user_prefs for each row execute function v2.set_updated_at();

create or replace function v2._user_prefs_limit() returns trigger
language plpgsql security definer set search_path = v2, public as $$
begin
  if (select count(*) from v2.user_prefs where user_id = new.user_id) >= 300 then
    raise exception 'Quá nhiều cài đặt cá nhân (tối đa 300).' using errcode = '54000';
  end if;
  return new;
end $$;
revoke all on function v2._user_prefs_limit() from public, anon, authenticated;
drop trigger if exists user_prefs_limit on v2.user_prefs;
create trigger user_prefs_limit before insert on v2.user_prefs for each row execute function v2._user_prefs_limit();

alter table v2.user_prefs enable row level security;
drop policy if exists user_prefs_select on v2.user_prefs;
drop policy if exists user_prefs_insert on v2.user_prefs;
drop policy if exists user_prefs_update on v2.user_prefs;
drop policy if exists user_prefs_delete on v2.user_prefs;
create policy user_prefs_select on v2.user_prefs for select to authenticated using (user_id = (select auth.uid()));
create policy user_prefs_insert on v2.user_prefs for insert to authenticated with check (user_id = (select auth.uid()));
create policy user_prefs_update on v2.user_prefs for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy user_prefs_delete on v2.user_prefs for delete to authenticated using (user_id = (select auth.uid()));

revoke all on v2.user_prefs from public, anon, authenticated;
grant select, insert, update, delete on v2.user_prefs to authenticated;
grant all on v2.user_prefs to service_role;

-- 3) Kĩ năng theo chủ đề CT GDPT 2018 ----------------------------------------------
insert into v2.skills (code, subject, grade, strand, topic, text, short, prereqs, provisional, position) values
${CT2018_SKILLS.map((s, i) => `  (${q(s.code)}, ${q(s.subject)}, ${s.grade}, 'CHU-DE', ${q(s.topic)}, ${q(s.text)}, ${q(s.short)}, '{}'::text[], true, ${10000 + i})`).join(',\n')}
on conflict (code) do update set subject = excluded.subject, grade = excluded.grade, strand = excluded.strand, topic = excluded.topic,
  text = excluded.text, short = excluded.short, prereqs = excluded.prereqs, provisional = excluded.provisional, position = excluded.position, updated_at = now();

commit;
`;
const old = existsSync(OUT) ? await fs.readFile(OUT, 'utf8') : null;
if (process.argv.includes('--check')) {
  if (old !== sql) { console.error('SQL 18 đã cũ — chạy: node tools/gen-sql18.mjs'); process.exit(1); }
  console.log('gen-sql18: không đổi');
} else {
  await fs.writeFile(OUT, sql);
  console.log(`gen-sql18: ${CT2018_SKILLS.length} kĩ năng → ${path.relative(ROOT, OUT)}`);
}
